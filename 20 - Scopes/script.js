/*3. Изучи, что такое hoisting в JavaScript и расскажи своими словами, что это такое и какие проблемы с ним связаны.
     Приведи примеры :) */

//Hoisting — это механизм в JavaScript, при котором объявления переменных и функций
//обрабатываются до выполнения кода.

//Переменные, объявленные через var, поднимаются и получают значение undefined,
//поэтому их можно вызвать до объявления, но они не имеют значения.
//Пример:

console.log(a); // undefined
var a = 5;

//Переменные, объявленные через let и const, тоже поднимаются, но находятся во
//временной мёртвой зоне (TDZ), поэтому при обращении к ним до объявления возникает ошибка.
//Пример:
console.log(b); // ReferenceError
let b = 10;

console.log(c); // ReferenceError
const c = 20;

//Функции, объявленные через function declaration, поднимаются полностью и могут
//быть вызваны до их объявления.
//Пример:

sayHello(); // "Hello"

function sayHello() {
    console.log('Hello');
}

//Функции, объявленные как function expression, ведут себя как переменные,
//поэтому их нельзя вызвать до объявления.
//Пример:

sayHi(); // ReferenceError

const sayHi = function() {
    console.log('Hi');
};

//Основные проблемы hoisting — это неожиданные undefined и ошибки ReferenceError,
//если использовать переменные до их объявления.


